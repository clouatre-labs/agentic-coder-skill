#!/usr/bin/env bash
# generate-coder-agents.sh -- regenerate coder-* agent files for pi, Claude Code,
# goose, and Vibe from per-role frontmatter fragments (tools/agents/{pi,claude,goose,vibe}-coder-<role>.yaml)
# and the shared body (agents-shared/coder-<role>.md).
#
# Usage:
#   scripts/generate-coder-agents.sh --check   # exit 1 on drift
#   scripts/generate-coder-agents.sh --write   # regenerate files in place

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
FRAGMENTS="$ROOT/tools/agents"
BODIES="$ROOT/agents-shared"
PI_DIR="$ROOT/agents/pi"
CLAUDE_DIR="$ROOT/agents/claude"
GOOSE_DIR="$ROOT/agents/goose"
VIBE_AGENTS_DIR="$ROOT/agents/vibe"
VIBE_PROMPTS_DIR="$ROOT/agents/vibe/prompts"
MODE="${1:---check}"

usage() { echo "usage: $0 (--check|--write)" >&2; exit 2; }
[ "$MODE" = "--check" ] || [ "$MODE" = "--write" ] || usage

drift=0
for agent in coder-scout coder-guard coder-build coder-check prose-polish; do
  body="$BODIES/$agent.md"
  [ -f "$body" ] || { echo "ERROR: missing body $body" >&2; exit 2; }
  for target in pi claude goose vibe; do
    frag="$FRAGMENTS/$target-$agent.yaml"
    out="$PI_DIR/$agent.md"
    [ "$target" = "claude" ] && out="$CLAUDE_DIR/$agent.md"
    [ "$target" = "goose" ] && out="$GOOSE_DIR/$agent.md"
    [ -f "$frag" ] || { echo "ERROR: missing fragment $frag" >&2; exit 2; }
    if [ "$target" = "vibe" ]; then
      # Vibe agents are TOML: the fragment maps to loader keys (agent_type,
      # display_name, description, safety, enabled_tools); the shared body
      # becomes the system prompt at ~/.vibe/prompts/<agent>.md, referenced
      # via system_prompt_id. No active_model: the unified harness ignores
      # per-agent models anyway, so delegates inherit the session model
      # (Mistral-hosted zai-glm-5-3 on the Mistral Pro subscription, pinned in
      # ~/.vibe/config.toml; thinking high is the ONLY working option on the
      # subscription path -- Vibe's mistral backend maps low->"none" and off->"off",
      # both REJECTED by zai-glm-5-3 per mistralai/mistral-vibe#1115).
      tmp_toml="$(mktemp)"
      {
        printf '# Generated by scripts/generate-coder-agents.sh from tools/agents/vibe-%s.yaml; do not edit.\n' "$agent"
        awk '
          /^[a-z_]+:/ {
            if (arr != "" && items) printf "]\n"
            key=$1; sub(/:$/, "", key)
            rest=$0; sub(/^[^:]*:[ ]?/, "", rest)
            if (rest != "") { printf "%s = %s\n", key, (rest ~ /^[0-9]+$/ ? rest : "\"" rest "\""); arr=""; items=0; next }
            arr=key; items=0; printf "%s = [", key; next
          }
          /^  - / { sub(/^  - /, ""); printf "%s\"%s\"", (items++ ? ", " : ""), $0; next }
          END { if (arr != "" && items) printf "]\n" }
        ' "$frag"
        printf 'system_prompt_id = "%s"\n' "$agent"
      } > "$tmp_toml"
      tmp_prompt="$(mktemp)"
      cp "$body" "$tmp_prompt"
      toml_out="$VIBE_AGENTS_DIR/$agent.toml"
      prompt_out="$VIBE_PROMPTS_DIR/$agent.md"
      if [ "$MODE" = "--write" ]; then
        mkdir -p "$(dirname "$toml_out")" "$(dirname "$prompt_out")"
        cp "$tmp_toml" "$toml_out"
        cp "$tmp_prompt" "$prompt_out"
      else
        if ! diff -u "$toml_out" "$tmp_toml" >/dev/null 2>&1; then
          echo "DRIFT: $toml_out differs from fragments + shared body" >&2
          diff -u "$toml_out" "$tmp_toml" >&2 || true
          drift=1
        fi
        if ! diff -u "$prompt_out" "$tmp_prompt" >/dev/null 2>&1; then
          echo "DRIFT: $prompt_out differs from shared body" >&2
          diff -u "$prompt_out" "$tmp_prompt" >&2 || true
          drift=1
        fi
      fi
      rm -f "$tmp_toml" "$tmp_prompt"
      continue
    fi
    tmp="$(mktemp)"
    {
      printf -- '---\n'
      cat "$frag"
      printf -- '---\n\n'
      cat "$body"
    } > "$tmp"
    if [ "$MODE" = "--write" ]; then
      mkdir -p "$(dirname "$out")"
      cp "$tmp" "$out"
    elif ! diff -u "$out" "$tmp" >/dev/null 2>&1; then
      echo "DRIFT: $out differs from fragments + shared body" >&2
      diff -u "$out" "$tmp" >&2 || true
      drift=1
    fi
    rm -f "$tmp"
  done
done

if [ "$MODE" = "--check" ]; then
  if [ "$drift" -ne 0 ]; then
    echo "Run: scripts/generate-coder-agents.sh --write" >&2
    exit 1
  fi
  echo "OK: generated coder agents match fragments + shared bodies"
fi
